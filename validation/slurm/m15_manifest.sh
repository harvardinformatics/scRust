#!/bin/bash
# Milestone M15: the manifest's section for M15's data (validation/manifest.toml), from the files on
# disk. From the repository's top directory:
#   bash validation/slurm/m15_manifest.sh <label> <cargo tests job> <loader tests job> > /path/to/section.toml
# and put the section in the manifest after M14's. Lists the one-time exports of the 150 saved
# DoubletFinder objects' re-clustering (validation/slurm/m15_export.sbatch), the panel's check
# records and summary rows (validation/slurm/m15_panel.sbatch), the T and P re-clustering checks in
# both profiles (validation/slurm/m15_recluster.sbatch), the memory measurements
# (validation/slurm/m15_memory.sbatch), the pinned binaries, and the runs of cargo test and of the
# loaders' tests. M15 made no new R reference runs: the exports read the saved objects.
set -euo pipefail
label=${1:?label}
cargo_job=${2:-}
tests_job=${3:-}
cat <<'EOF'
# M15: clustering on the fly and the singlets' re-clustering (plan C3h, C5: K12, C6) ---------------
#
# Milestone M15. Generated by validation/slurm/m15_manifest.sh from the files on disk (do not edit
# by hand). Results: docs/validation/clustering.md ("M15"). No new R reference runs: the exports
# read the saved objects' metadata.
#
#   data/clustering/doubletfinder_<object>/{input,saved}/   validation/R/export_clustering.R at level
#               labels (validation/slurm/m15_export.sbatch): the saved DoubletFinder object's
#               metadata.tsv and levels files (the workflow's re-clustering of the singlets),
#               object.json, a copy of its marker table; input/ links to M7's export of its RNA
#               counts (data/doubletfinder/<object>/saved/singlets/), checked against the object
#   data/doubletfinder/<object>/rust/<label>/production/   validation/slurm/m15_panel.sbatch: the
#               checks (checks/*.json), the summary row (row.tsv), /usr/bin/time -v of the four
#               runs (time_*.txt) and the fingerprint
#   data/doubletfinder/<object>/rust/<label>/<profile>_recluster/   validation/slurm/m15_recluster.sbatch
#               on T and P: the checks (checks/*.json), time_*.txt, the fingerprint
#   data/doubletfinder/<object>/rust/<label>{,-rc}/memory/memory.tsv   validation/slurm/m15_memory.sbatch
#               (clustering on the fly; with MODES="given recluster2 inprocess", the re-clustering)
#   data/doubletfinder/logs/bin/scrust-<label>, data/benchmarks/bin/scrust-<commit>   the binaries
#   data/clustering/m15/cargo_tests/<job>/results.tsv, data/clustering/m15/tests/<job>/{r,python}.log

EOF
entry() {  # <path> <role> <note> [<dataset>] [<tier>]
    local p=$1
    printf '[[file]]\npath = "%s"\nsha256 = "%s"\nbytes = %s\ntool = "clustering"\nrole = "%s"\nmilestone = "M15"\nnote = "%s"\n' \
        "$p" "$(sha256sum "$p" | cut -d' ' -f1)" "$(stat -c %s "$p")" "$2" "$3"
    [ -n "${4:-}" ] && printf 'dataset = "%s"\n' "$4"
    [ -n "${5:-}" ] && printf 'tier = "%s"\n' "$5"
    printf '\n'
}
# the exports of the saved DoubletFinder objects' re-clustering
awk -F'\t' 'NR == 1 { for (c = 1; c <= NF; c++) h[$c] = c; next } $h["kind"] == "doubletfinder" { print $h["object"], $h["saved"] }' \
    validation/clustering_panel.tsv | while read -r obj saved; do
    d=data/clustering/$obj
    for f in saved/metadata.tsv saved/seurat_clusters_levels.txt saved/SCT_snn_res.0.8_levels.txt saved/idents_levels.txt saved/object.json saved/markergenes.csv; do
        [ -f "$d/$f" ] && entry "$d/$f" saved-output "the saved DoubletFinder object's re-clustering ($saved), exported at level labels: $(basename "$f")" "$obj" full-panel
    done
    for f in input/export.json input/assay.txt export_run.json export_time_v.txt; do
        [ -f "$d/$f" ] && entry "$d/$f" run-record "the export's record: $(basename "$f")" "$obj" full-panel
    done
done
# the panel
for d in data/doubletfinder/*/rust/"$label"/production; do
    [ -d "$d" ] || continue
    obj=$(echo "$d" | cut -d/ -f3)
    for f in "$d"/checks/*.json "$d"/checks/*.md "$d/row.tsv"; do
        [ -f "$f" ] && entry "$f" check "K12 and the re-clustering on the panel: $(basename "$f")" "$obj" full-panel
    done
    for f in "$d"/time_*.txt "$d/fingerprint.json" "$d/node_features.txt"; do
        [ -f "$f" ] && entry "$f" run-record "the panel's runs: $(basename "$f")" "$obj" full-panel
    done
done
# T and P, both profiles
for d in data/doubletfinder/*/rust/"$label"/*_recluster; do
    [ -d "$d" ] || continue
    obj=$(echo "$d" | cut -d/ -f3)
    prof=$(basename "$d" _recluster)
    for f in "$d"/checks/*.json; do
        [ -f "$f" ] && entry "$f" check "the re-clustering's checks, $prof profile: $(basename "$f")" "$obj"
    done
    for f in "$d"/time_*.txt "$d/fingerprint.json"; do
        [ -f "$f" ] && entry "$f" run-record "the re-clustering's runs, $prof profile: $(basename "$f")" "$obj"
    done
done
for f in data/doubletfinder/*/rust/"$label"/memory/memory.tsv; do
    [ -f "$f" ] && entry "$f" check "peak memory of clustering on the fly, settled or not, and with the labels given, repeated" "$(echo "$f" | cut -d/ -f3)"
done
for f in data/doubletfinder/*/rust/"$label"-rc/memory/memory.tsv; do
    [ -f "$f" ] && entry "$f" check "peak memory of the whole rule in process and of the two commands, repeated" "$(echo "$f" | cut -d/ -f3)"
done
for f in data/doubletfinder/logs/bin/scrust-"$label" data/benchmarks/bin/scrust-*; do
    case $f in *b6f6e4e) continue ;; esac
    [ -f "$f" ] && entry "$f" run-record "a pinned scrust binary of M15's runs"
done
if [ -n "$cargo_job" ]; then
    f=data/clustering/m15/cargo_tests/$cargo_job/results.tsv
    [ -f "$f" ] && entry "$f" check "cargo test --workspace, debug and release, every test's outcome"
fi
if [ -n "$tests_job" ]; then
    for f in data/clustering/m15/tests/"$tests_job"/r.log data/clustering/m15/tests/"$tests_job"/python.log; do
        [ -f "$f" ] && entry "$f" check "the loaders' own tests: $(basename "$f")"
    done
    # the binary the loaders' tests ran, from the job's log (when it is not the label's)
    tb=$(sed -n 's/^binary=\([^ ]*\) .*/\1/p' data/clustering/logs/m15/scrust-m15-tests-"$tests_job".sbatch.log 2>/dev/null | head -n 1)
    tb=${tb#"$PWD"/}
    [ -n "$tb" ] && [ -f "$tb" ] && [ "$tb" != "data/doubletfinder/logs/bin/scrust-$label" ] && entry "$tb" run-record "the pinned scrust binary of the loaders' tests"
fi

#!/bin/bash
# Milestone M14: the manifest's section for M14's data (validation/manifest.toml), from the files on
# disk. From the repository's top directory:
#   bash validation/slurm/m14_manifest.sh <label> <cargo tests job> <package tests job> > /path/to/section.toml
# and put the section in the manifest after M13's. Lists, for the exports of the validation runs
# <label> that M14 loaded: each loader comparison's tables (R: k11.tsv, files.tsv, roundtrip.tsv,
# compare.json; Python: k11_anndata.tsv, files_anndata.tsv, roundtrip_anndata.tsv,
# compare_anndata.json), the 10x readers on each export, each object's marker check (K13: the
# combined table and markers.json), the M17-style comparisons, and the runs of cargo test and of the
# loaders' own tests. M14 made no R reference runs and no Rust validation runs: it loads M13's.
set -euo pipefail
label=${1:?label}
cargo_job=${2:-}
tests_job=${3:-}
cat <<'EOF'
# M14: the loaders (plan C3g, C5: K11, K13, C6) ---------------------------------------------------
#
# Milestone M14. Generated by validation/slurm/m14_manifest.sh from the files on disk (do not edit
# by hand). Results: docs/validation/clustering.md ("M14"). M14 made no R reference runs and no
# Rust validation runs: it loads M13's exports (data/clustering/<object>/rust/<label>/<profile>/run)
# and scrust doubletfinder outputs (data/doubletfinder/<input>/rust/<label>/<profile>/run).
#
#   data/clustering/<object>/loaders/<label>/<profile>/r/   validation/R/loader_compare.R: the Seurat
#               and SingleCellExperiment loaders against the saved .rds (k11.tsv, one row per
#               component), every value read against the files (files.tsv), the .rds round trips
#               (roundtrip.tsv), compare.json (validation/slurm/m14_loaders.sbatch)
#   data/clustering/<object>/loaders/<label>/<profile>/python/   validation/python/loader_compare.py:
#               the AnnData loader against M8's export of the saved object (k11_anndata.tsv,
#               files_anndata.tsv, roundtrip_anndata.tsv, compare_anndata.json)
#   data/clustering/<object>/loaders/<label>/<profile>/guard/   Seurat's Read10X and scanpy's
#               read_10x_mtx (every prefix) on every directory of the export
#   data/clustering/<object>/loaders/<label>/<profile>/markers/   K13: validation/R/markers_from_loader.R,
#               the combined marker table and markers.json (validation/slurm/m14_markers.sbatch)
#   data/clustering/<object>/loaders/<label>/<profile>/m17/   M17's comparison, timed
#               (validation/slurm/m14_m17.sbatch)
#   data/doubletfinder/<input>/loaders/<label>/<profile>/{r,python}/   the loaders on scrust
#               doubletfinder's outputs against the saved DoubletFinder objects
#   data/clustering/m14/cargo_tests/<job>/   cargo test --workspace, debug and release
#               (validation/slurm/m14_cargo_tests.sbatch): debug.txt, release.txt, results.tsv
#   data/clustering/m14/tests/<job>/   the loaders' own tests (validation/slurm/m14_tests.sbatch):
#               r.log, python.log

EOF
entry() {  # <path> <role> <note> [<dataset>]
    local p=$1
    printf '[[file]]\npath = "%s"\nsha256 = "%s"\nbytes = %s\ntool = "clustering"\nrole = "%s"\nmilestone = "M14"\nnote = "%s"\n' \
        "$p" "$(sha256sum "$p" | cut -d' ' -f1)" "$(stat -c %s "$p")" "$2" "$3"
    [ -n "${4:-}" ] && printf 'dataset = "%s"\n' "$4"
    printf '\n'
}
for d in data/clustering/*/loaders/"$label"/* data/doubletfinder/*/loaders/"$label"/*; do
    [ -d "$d" ] || continue
    obj=$(echo "$d" | cut -d/ -f3)
    profile=$(basename "$d")
    for f in r/k11.tsv r/files.tsv r/roundtrip.tsv r/compare.json; do
        [ -f "$d/$f" ] && entry "$d/$f" check "K11, R loaders ($profile export): $(basename "$f")" "$obj"
    done
    for f in python/k11_anndata.tsv python/files_anndata.tsv python/roundtrip_anndata.tsv python/compare_anndata.json; do
        [ -f "$d/$f" ] && entry "$d/$f" check "K11, Python loader ($profile export): $(basename "$f")" "$obj"
    done
    for f in guard/read10x_seurat.tsv guard/read10x_scanpy.tsv; do
        [ -f "$d/$f" ] && entry "$d/$f" check "K11, the 10x readers on the $profile export: $(basename "$f" .tsv | sed 's/read10x_//')" "$obj"
    done
    if [ -f "$d/markers/markers.json" ]; then
        entry "$d/markers/markers.json" check "K13 ($profile export): the marker steps on the Seurat loader's object" "$obj"
        for t in "$d"/markers/*_markergenes.csv; do
            entry "$t" check "K13 ($profile export): the combined marker table" "$obj"
        done
    fi
    for f in m17/k11.tsv m17/compare.json; do
        [ -f "$d/$f" ] && entry "$d/$f" check "M17's comparison through the Seurat loader ($profile export), timed: $(basename "$f")" "$obj"
    done
done
if [ -n "$cargo_job" ]; then
    for f in data/clustering/m14/cargo_tests/"$cargo_job"/results.tsv; do
        [ -f "$f" ] && entry "$f" check "cargo test --workspace, debug and release, every test's outcome"
    done
fi
if [ -n "$tests_job" ]; then
    for f in data/clustering/m14/tests/"$tests_job"/r.log data/clustering/m14/tests/"$tests_job"/python.log; do
        [ -f "$f" ] && entry "$f" check "the loaders' own tests: $(basename "$f" .log)"
    done
fi

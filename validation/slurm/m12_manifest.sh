#!/bin/bash
# Milestone M12: the manifest's section for M12's data (validation/manifest.toml), from the files
# on disk. From the repository's top directory:
#   bash validation/slurm/m12_manifest.sh [<label>] > /path/to/section.toml
# and put the section in the manifest before "# FindClusters (plan C4 and C7)", after M11's. Lists
# the pinned binaries (the decision point's survey and the validation and benchmark runs), the
# certificate survey's tables, the R-vs-R floor of the neighbour lists measured cell by cell, and
# the run of cargo test under another kernel. M12 made no R runs. Rust's validation and benchmark
# runs (data/clustering/<object>/rust/<label>/) and the survey's runs
# (data/clustering/m12_certificate/m12-survey/<object>/) are not listed, as in M9 to M11; their
# results are in docs/validation/clustering.md, clustering_m12.tsv and the survey's tables.
set -euo pipefail
label=${1:-m12-4231635}
survey_jobs="61647015 61647016"
kernel_job=61652585
cat <<'EOF'
# M12: neighbourhood purity (plan C3e, C5: K9, C6) ------------------------------------------------
#
# Milestone M12. Generated by validation/slurm/m12_manifest.sh from the files on disk (do not edit
# by hand). Results: docs/validation/clustering.md. M12 made no R runs.
#
#   data/clustering/bin/scrust-m12-survey   the binary of the decision point's survey (built from
#               M12's tree before its first commit; flags without kinds)
#   data/clustering/m12_certificate/m12-survey/certificate.<job>.tsv   the survey: neighborPurity
#               and its certificate on R's own embeddings and labels, both profiles' instrumented
#               runs of the 34 objects (validation/slurm/m12_certificate.sbatch), one row per run
#   data/clustering/bin/scrust-m12-<commit>   the binary of the validation and benchmark runs
#   data/clustering/floor_kernel_m12_lists.tsv   the R-vs-R floor of purity's neighbour lists, cell
#               by cell, Haswell against SapphireRapids on Sapphire Rapids, the 28 objects whose
#               runs kept the lists (validation/slurm/m12_lists_floor.sh); [clustering.floor.kernel]
#               K9_neighbors
#   data/clustering/m12_kernel_tests/<kernel>/   cargo test under another kernel than the fixtures'
#               (validation/slurm/m12_kernel_tests.sbatch): cargo_test.txt, results.tsv

EOF
entry() {  # <path> <role> <note> [<job>]
    local p=$1
    printf '[[file]]\npath = "%s"\nsha256 = "%s"\nbytes = %s\ntool = "clustering"\nrole = "%s"\nmilestone = "M12"\nnote = "%s"\n' \
        "$p" "$(sha256sum "$p" | cut -d' ' -f1)" "$(stat -c %s "$p")" "$2" "$3"
    [ -n "${4:-}" ] && printf 'slurm_job_id = "%s"\n' "$4"
    printf '\n'
}
b=data/clustering/bin/scrust-m12-survey
[ -f "$b" ] && entry "$b" binary "scrust built from M12's tree before its first commit: the decision point's certificate survey"
for j in $survey_jobs; do
    f=data/clustering/m12_certificate/m12-survey/certificate.$j.tsv
    [ -f "$f" ] && entry "$f" check "neighborPurity's certificate on R's own embeddings and labels, both profiles' instrumented runs: one row per run" "$j"
done
b=data/clustering/bin/scrust-$label
[ -f "$b" ] && entry "$b" binary "scrust built from commit ${label#m12-}: the M12 validation and benchmark runs"
f=data/clustering/floor_kernel_m12_lists.tsv
[ -f "$f" ] && entry "$f" check "R-vs-R floor of neighborPurity's neighbour lists, cell by cell (Haswell against SapphireRapids, Sapphire Rapids)"
for f in data/clustering/m12_kernel_tests/*/cargo_test.txt data/clustering/m12_kernel_tests/*/results.tsv; do
    [ -f "$f" ] && entry "$f" check "cargo test --workspace --release under kernel $(basename "$(dirname "$f")")" "$kernel_job"
done
exit 0

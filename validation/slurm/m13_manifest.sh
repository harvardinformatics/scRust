#!/bin/bash
# Milestone M13: the manifest's section for M13's data (validation/manifest.toml), from the files on
# disk. From the repository's top directory:
#   bash validation/slurm/m13_manifest.sh <label> <kernel job> <step-1 label> > /path/to/section.toml
# and put the section in the manifest after M12's. Lists the pinned binary of the validation and
# benchmark runs, the committed fixtures M13 adds (tests/fixtures/clustering/<object>/reference/k10.tsv
# and, for the two base objects, R's model for K10 teacher-forced) with their sources, the guard
# tests' tables (Seurat's Read10X and scanpy's read_10x_mtx on exports), the check that Step 1's
# files are unchanged, and the run of cargo test under another kernel. M13 made no R runs. Rust's
# validation and benchmark runs (data/clustering/<object>/rust/<label>/,
# data/doubletfinder/<object>/rust/<label>/) are not listed, as in M9 to M12; their results are in
# docs/validation/clustering.md, clustering_m13.tsv and clustering_m13_bench.tsv.
set -euo pipefail
label=${1:?label}
kernel_job=${2:-}
step1=${3:-$label}
cat <<'EOF'
# M13: the corrected counts and the export (plan C3f, C5: K10, C6) --------------------------------
#
# Milestone M13. Generated by validation/slurm/m13_manifest.sh from the files on disk (do not edit
# by hand). Results: docs/validation/clustering.md. M13 made no R runs.
#
#   data/clustering/bin/scrust-m13-<commit>   the binary of the validation and benchmark runs
#   tests/fixtures/clustering/<object>/reference/k10.tsv   committed: R's corrected counts as the
#               portable instrumented run wrote them, by the SHA-256 of the files' data lines and
#               R's digests (validation/slurm/fixtures_m13.sh); source: that run's sct/
#   tests/fixtures/clustering/<base object>/reference/stages/vst/{model_pars_fit,cell_attr}.tsv.gz,
#               reference/stages/K10_genes.npy.gz   committed: R's model for K10 teacher-forced
#               (gzip -n -9 of the portable instrumented run's files)
#   data/clustering/<object>/rust/<label>/guard/read10x_{seurat,scanpy}.tsv   the guard tests
#               (validation/slurm/m13_guard.sbatch: Seurat's Read10X in the production R env,
#               scanpy's read_10x_mtx in envs/loaders-py.yml), one row per directory (and prefix)
#   data/doubletfinder/compare/m13_step1_<label>.tsv   scrust doubletfinder with M13's binary
#               against M6b's and M7's runs, every file byte for byte
#               (validation/slurm/m13_doubletfinder.sbatch)
#   data/clustering/m13_kernel_tests/<kernel>/   cargo test under another kernel than the fixtures'
#               (validation/slurm/m13_kernel_tests.sbatch): cargo_test.txt, results.tsv

EOF
entry() {  # <path> <role> <note> [<job>] [<source>]
    local p=$1
    printf '[[file]]\npath = "%s"\nsha256 = "%s"\nbytes = %s\ntool = "clustering"\nrole = "%s"\nmilestone = "M13"\nnote = "%s"\n' \
        "$p" "$(sha256sum "$p" | cut -d' ' -f1)" "$(stat -c %s "$p")" "$2" "$3"
    [ -n "${4:-}" ] && printf 'slurm_job_id = "%s"\n' "$4"
    [ -n "${5:-}" ] && printf 'source = "%s"\n' "$5"
    printf '\n'
}
b=data/clustering/bin/scrust-$label
[ -f "$b" ] && entry "$b" binary "scrust built from commit ${label#m13-}: the M13 validation, guard and benchmark runs"
for f in tests/fixtures/clustering/*/reference/k10.tsv; do
    o=$(echo "$f" | cut -d/ -f4)
    entry "$f" fixture "R's corrected counts (K10) by the SHA-256 of the files' data lines and R's digests, portable instrumented run" "" "data/clustering/$o/runs/instrumented-portable-sapphirerapids/sct"
done
for f in tests/fixtures/clustering/*/reference/stages/vst/*.tsv.gz tests/fixtures/clustering/*/reference/stages/K10_genes.npy.gz; do
    [ -f "$f" ] || continue
    o=$(echo "$f" | cut -d/ -f4)
    rel=${f#tests/fixtures/clustering/$o/reference/}
    entry "$f" fixture "R's model for K10 teacher-forced (gzip -n -9 of the source)" "" "data/clustering/$o/runs/instrumented-portable-sapphirerapids/${rel%.gz}"
done
for f in data/clustering/*/rust/"$label"/guard/read10x_seurat.tsv data/clustering/*/rust/"$label"/guard/read10x_scanpy.tsv; do
    [ -f "$f" ] && entry "$f" check "the export's guard: $(basename "$f" .tsv | sed 's/read10x_//') on every directory of an export and of scrust sctransform --corrected-counts' output"
done
f=data/doubletfinder/compare/m13_step1_$step1.tsv
[ -f "$f" ] && entry "$f" check "scrust doubletfinder with M13's binary against M6b's and M7's runs, every file byte for byte"
f=data/doubletfinder/compare/m11_verdicts_$label.tsv
[ -f "$f" ] && entry "$f" check "Step 1's validation reports re-graded with M13's binary (validation/slurm/m11_doubletfinder.sbatch), check by check"
for f in data/clustering/m13_kernel_tests/*/cargo_test.txt data/clustering/m13_kernel_tests/*/results.tsv; do
    [ -f "$f" ] && entry "$f" check "cargo test --workspace --release under kernel $(basename "$(dirname "$f")")" "$kernel_job"
done
exit 0

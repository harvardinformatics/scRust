#!/bin/bash
# Milestone M11: the manifest's section for M11's data (validation/manifest.toml), from the files
# on disk. From the repository's top directory:
#   bash validation/slurm/m11_manifest.sh > /path/to/section.toml
# and put the section in the manifest before "# FindClusters (plan C4 and C7)". Lists the committed
# fixture of the kernel checks, the pinned binary, the R-vs-R floor measurements, the run of cargo
# test under another kernel and the DoubletFinder re-grading's summary. Rust's validation and
# benchmark runs (data/clustering/<object>/rust/<label>/) are not listed, as in M9 and M10; their
# results are in docs/validation/clustering.md and clustering_m11.tsv.
set -euo pipefail
label=${1:-m11-eedf376}
cat <<'EOF'
# M11: the clustering chain and kernel-gated grading (plan A5b, C5, C6) ---------------------------
#
# Milestone M11. Generated by validation/slurm/m11_manifest.sh from the files on disk (do not edit
# by hand). Results: docs/validation/clustering.md.
#
#   tests/fixtures/kernels.tsv   the OpenBLAS kernel each BLAS-dependent fixture without its own
#               run record was made under (rcompat::blas::require_fixture_kernel)
#   data/clustering/bin/scrust-m11-<commit>   the binary of the validation and benchmark runs
#   data/clustering/floor_kernel_m11/, data/doubletfinder/compare/floor_kernel_m11/   the R-vs-R
#               floor across OpenBLAS kernels, measured by `scrust validate floor` on M8's and M2's
#               instrumented runs in both profiles (validation/slurm/m11_floor.sbatch): pairs.tsv,
#               blocks.tsv (one row per array, context and pair), summary.md (the maxima behind
#               [clustering.floor.kernel] and [doubletfinder.floor.kernel])
#   data/clustering/m11_kernel_tests/<kernel>/   cargo test under another kernel than the fixtures'
#               (validation/slurm/m11_kernel_tests.sbatch): cargo_test.txt, results.tsv
#   data/doubletfinder/compare/m11_verdicts_<label>.tsv   M6's and M7's Rust runs re-graded with
#               kernel gating, verdict by verdict (validation/slurm/m11_doubletfinder.sbatch)

EOF
entry() {  # <path> <role> <note> [<job>]
    local p=$1
    printf '[[file]]\npath = "%s"\nsha256 = "%s"\nbytes = %s\ntool = "clustering"\nrole = "%s"\nmilestone = "M11"\nnote = "%s"\n' \
        "$p" "$(sha256sum "$p" | cut -d' ' -f1)" "$(stat -c %s "$p")" "$2" "$3"
    [ -n "${4:-}" ] && printf 'slurm_job_id = "%s"\n' "$4"
    printf '\n'
}
entry tests/fixtures/kernels.tsv fixture "the OpenBLAS kernel of each BLAS-dependent fixture without its own run record"
for b in data/clustering/bin/scrust-"$label"; do
    [ -f "$b" ] && entry "$b" binary "scrust built from commit ${label#m11-}: the M11 validation and benchmark runs"
done
for d in data/clustering/floor_kernel_m11 data/doubletfinder/compare/floor_kernel_m11; do
    for f in pairs.tsv blocks.tsv summary.md time_v.txt; do
        [ -f "$d/$f" ] && entry "$d/$f" check "R-vs-R floor across OpenBLAS kernels (Haswell against SapphireRapids, Sapphire Rapids): $f" 60798602
    done
done
for f in data/clustering/m11_kernel_tests/*/cargo_test.txt data/clustering/m11_kernel_tests/*/results.tsv; do
    [ -f "$f" ] && entry "$f" check "cargo test --workspace --release under kernel $(basename "$(dirname "$f")")" 60815653
done
f=data/doubletfinder/compare/m11_verdicts_$label.tsv
[ -f "$f" ] && entry "$f" check "scrust validate doubletfinder with kernel gating on M6's and M7's Rust runs: the verdicts, check by check" 60804010

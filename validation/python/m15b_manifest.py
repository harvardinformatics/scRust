"""Milestone M15b: the manifest's section for M15b's data (validation/manifest.toml), from the files
on disk. From the repository's top directory:

  PYTHONNOUSERSITE=1 .envs/loaders-py/bin/python -I validation/python/m15b_manifest.py \\
      --label <label> [--revalidate <label>] [--cargo-job <job>] [--tests-job <job>] [--bin <path>]... \\
      > /path/to/section.toml

and put the section in the manifest after M15's. Lists:
  - the R reference runs of the chain with vars.to.regress (validation/slurm/m15b_references.sbatch,
    one per row of validation/m15b_cases.tsv and profile): a [[run]] table each, and a [[file]]
    table for each of their files, a file identical (same relative path, same sha256) to one of
    another run of the same object and case listed once, with identical_on;
  - the cases' inputs (data/clustering/m15b/inputs/), the R vectors' log, the committed fixtures;
  - the exports of the saved objects' percent.mt (validation/slurm/m15b_saved.sbatch) and the check
    of how the saved DoubletFinder objects made it (validation/slurm/m15b_percent_mt_sct.sbatch);
  - the checks: scrust's validation runs (validation/slurm/m15b_cluster.sbatch; with
    --revalidate, validation/slurm/m15b_revalidate.sbatch's reports), percent.mt against the saved
    objects (validation/slurm/m15b_saved_rust.sbatch), the R-vs-R measurement
    (validation/python/m15b_floor.py), the defaults against M15's runs
    (validation/slurm/m15b_unchanged.sbatch), DoubletFinder's routes with the options
    (validation/slurm/m15b_recluster.sbatch), cargo test and the loaders' tests;
  - the pinned binaries.
Scrust's own output directories (run/) are not listed: they are remade from the recipes.
"""

import argparse
import csv
import glob
import hashlib
import json
import os
import re
import sys

MILESTONE = "M15b"


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def q(s):
    return json.dumps(str(s), ensure_ascii=False)


def table(kind, fields):
    out = [f"[[{kind}]]"]
    for k, v in fields:
        if v is None:
            continue
        if isinstance(v, bool):
            out.append(f"{k} = {'true' if v else 'false'}")
        elif isinstance(v, int):
            out.append(f"{k} = {v}")
        elif isinstance(v, list):
            out.append(f"{k} = [{', '.join(q(x) for x in v)}]")
        else:
            out.append(f"{k} = {q(v)}")
    return "\n".join(out) + "\n"


def file_entry(path, role, note, **extra):
    fields = [("path", path), ("sha256", sha256(path)), ("bytes", os.path.getsize(path)), ("tool", "clustering"),
              ("role", role), ("milestone", MILESTONE), ("note", note)]
    fields += list(extra.items())
    return table("file", fields)


def time_v(path):
    rss = elapsed = None
    if os.path.isfile(path):
        for line in open(path):
            m = re.match(r"\s*Maximum resident set size \(kbytes\): (\d+)", line)
            if m:
                rss = int(m.group(1))
            m = re.match(r"\s*Elapsed \(wall clock\) time \(h:mm:ss or m:ss\): (\S+)", line)
            if m:
                elapsed = m.group(1)
    return rss, elapsed


STAGE = [
    ("sct/scale_data", "K1"), ("sct/variable_features", "K1"), ("sct/model", "K1"), ("sct/corrected_counts", "K10"),
    ("sct/sct_", "K10"), ("pca/", "K2"), ("graphs/", "K6"), ("seurat_clusters_levels", "K7"),
    ("SCT_snn_res", "K7"), ("idents_levels", "K7"), ("cluster_ids", "K7"), ("nclusters", "K7"), ("metadata.tsv", "K14"),
]


def stage_of(rel):
    for prefix, st in STAGE:
        if rel.startswith(prefix) or os.path.basename(rel).startswith(prefix):
            return st
    return None


def r_runs(out, cases):
    header = """# M15b: SCTransform's vars.to.regress and the workflow's percent.mt (plan C3j, C5: K14, C6) --------
#
# Milestone M15b. Generated by validation/python/m15b_manifest.py from the files on disk (do not
# edit by hand). Results: docs/validation/clustering.md ("M15b"). New R reference runs, approved for
# M15b: the workflow's chain with vars.to.regress, in the production R env, by sbatch.
#
#   validation/m15b_cases.tsv   the cases (validation/python/m15b_cases.py): each object of tiers T
#               and P with a case pm (percent.mt by the workflow's pattern), ids (by a list of ids),
#               ids_ncount (percent.mt and nCount_RNA) and meta (a column of --metadata), as fits it;
#               rust_mt_genes is what scrust is given where R's pattern finds no feature
#   data/clustering/m15b/inputs/<object>/   the cases' inputs: mt_genes.txt (the ids), zero_genes.txt
#               (features without counts: R's all-zero percent.mt), metadata.tsv (a numeric column,
#               score, written with R's number formats and a leading +)
#   data/clustering/m15b/runs/<object>/<case>/direct-<profile>-<cpu arch>/   R's runs
#               (validation/slurm/m15b_references.sbatch: validation/R/reference_clustering.R with
#               --vars-to-regress, --percent-mt, --mt-genes, --metadata), M8's layout; a [[run]]
#               table each, and a [[file]] table per file; a file identical to one of another run of
#               the same case (same relative path and sha256) is listed once, with identical_on
#   data/clustering/logs/m15b/regress_vectors.txt   validation/R/regress_vectors.R's log: the code
#               path's functions identical to the source tarball's, the QR vectors, the names
#   data/clustering/m15b/saved/<object>/   validation/slurm/m15b_saved.sbatch
#               (validation/R/export_percent_mt.R): the saved objects' percent.mt, 34 clustering and
#               150 DoubletFinder objects
#   data/clustering/m15b/percent_mt_sct/<object>.json   validation/slurm/m15b_percent_mt_sct.sbatch:
#               PercentageFeatureSet() on the SCT and on the RNA assay of each saved DoubletFinder
#               input, at the singlets, against the saved percent.mt
#   data/clustering/m15b/percent_mt_rna/<object>.json   the same on the 30 with mitochondrial
#               features, also against scrust's percent.mt (validation/slurm/m15b_percent_mt_sct.sbatch
#               percent_mt_rna <label>)
#   data/clustering/m15b/rust/<label>/<object>/<case>/<profile>/   validation/slurm/m15b_cluster.sbatch:
#               scrust validate cluster's reports against both R runs, the refusal, the records
#   data/clustering/m15b/revalidate/<label>/...   validation/slurm/m15b_revalidate.sbatch: the same runs
#               validated again by the final binary
#   data/clustering/m15b/saved_rust/<label>/   validation/slurm/m15b_saved_rust.sbatch and
#               validation/python/m15b_percent_mt.py: scrust's percent.mt against the saved objects'
#   data/clustering/m15b/floor/   validation/python/m15b_floor.py: R against R across kernels with
#               the regression, every case, array and direction (r_vs_r.tsv), and the maxima by tier
#               with the case that sets each ([clustering.floor.kernel_regressed]; summary.md)
#   data/clustering/m15b/unchanged/<label>/   validation/slurm/m15b_unchanged.sbatch: without the
#               options, M15's runs (validation/slurm/m15_recluster.sbatch) route by route
#   data/doubletfinder/<object>/rust/<label>/<profile>_m15b/   validation/slurm/m15b_recluster.sbatch:
#               DoubletFinder's two clusterings with the options, in process against the commands
#   data/clustering/m15b/cargo_tests/<job>/, data/clustering/m15b/tests/<job>/   cargo test, the
#               loaders' tests
#   tests/fixtures/rcompat/linpack_*.tsv.gz, tests/fixtures/clustering/{m15b,percent_mt}/   the
#               committed fixtures (their README)
#   tests/fixtures/kernels.tsv   extended by M15b (the linpack fixtures' rows); it keeps its one
#               entry, M11's, updated to the file as M15b left it
#   validation/python/check_manifest.py   the whole manifest against the files on disk: every
#               entry's size, the committed files' SHA-256 (with --hash M15b, M15b's entries' too)

"""
    out.append(header)
    seen = {}
    for i, c in enumerate(cases, start=1):
        base = os.path.join("data", "clustering", "m15b", "runs", c["object"], c["case"])
        for d in sorted(glob.glob(os.path.join(base, "direct-*"))):
            if ".partial" in d or not os.path.isdir(d):
                continue
            name = os.path.basename(d)
            profile = name.split("-")[1]
            fp = {}
            if os.path.isfile(os.path.join(d, "fingerprint_wrapper.json")):
                fp = json.load(open(os.path.join(d, "fingerprint_wrapper.json")))
            s = json.load(open(os.path.join(d, "summary.json")))
            run = s.get("run", {})
            rfp = run.get("fingerprint", {})
            rss, el = time_v(os.path.join(d, "time_v.txt"))
            rid = f"clustering/m15b/{c['object']}/{c['case']}/{name}"
            out.append(table("run", [
                ("id", rid), ("tool", "clustering"), ("kind", "direct"), ("milestone", MILESTONE), ("dataset", c["object"]),
                ("tier", c["tier"]), ("path", d), ("profile", profile), ("case", c["case"]),
                ("vars_to_regress", c["vars_to_regress"].split(",")), ("percent_mt", c["percent_mt"] == "yes"),
                ("mt_genes", c["mt_genes"] or None), ("metadata", c["metadata"] or None),
                ("umap", run.get("umap")), ("assay", run.get("assay")), ("level", run.get("level")),
                ("recipe", f"validation/slurm/m15b_references.sbatch {profile} (array task {i}: validation/m15b_cases.tsv row {i})"),
                ("slurm_job_id", run.get("slurm_job_id") or fp.get("SLURM_JOB_ID")),
                ("env", "the production R env (smk-conda-envs/d3ca7f730a70e6f748bb65a12a5ed3f9_)"),
                ("node", fp.get("host") or rfp.get("host")), ("cpu_model", fp.get("cpu_model") or rfp.get("cpu_model")),
                ("openblas_core", fp.get("openblas_corename") or rfp.get("openblas_corename")),
                ("openblas_threads", fp.get("openblas_num_threads") or rfp.get("openblas_num_threads")),
                ("glibc", fp.get("glibc") or rfp.get("glibc")), ("R", rfp.get("R")),
                ("max_rss_kib", rss), ("elapsed", el),
            ]))
            out.append("\n")
            for f in sorted(glob.glob(os.path.join(d, "**", "*"), recursive=True)):
                if not os.path.isfile(f):
                    continue
                rel = os.path.relpath(f, d)
                record = rel in ("summary.json", "time_v.txt", "fingerprint_wrapper.json")
                key = (c["object"], c["case"], rel)
                h = sha256(f)
                if not record and key in seen and seen[key][0] == h:
                    seen[key][1].append(rid)
                    continue
                entry = {"path": f, "sha256": h, "bytes": os.path.getsize(f), "rid": rid, "rel": rel, "record": record, "same": []}
                out.append(entry)
                if not record:
                    seen[key] = (h, entry["same"])
    return out


def flush(out):
    for x in out:
        if isinstance(x, str):
            sys.stdout.write(x)
        else:
            fields = [("path", x["path"]), ("sha256", x["sha256"]), ("bytes", x["bytes"]), ("tool", "clustering"),
                      ("role", "run-record" if x["record"] else "reference"), ("milestone", MILESTONE)]
            st = None if x["record"] else stage_of(x["rel"])
            if st:
                fields.append(("stage", st))
            fields.append(("run", x["rid"]))
            if x["same"]:
                fields.append(("identical_on", x["same"]))
            sys.stdout.write(table("file", fields) + "\n")


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--label", required=True, help="the validation runs' label (m15b_cluster.sbatch and the others)")
    p.add_argument("--revalidate")
    p.add_argument("--cargo-job")
    p.add_argument("--tests-job")
    p.add_argument("--bin", action="append", default=[])
    a = p.parse_args()
    cases = list(csv.DictReader(open("validation/m15b_cases.tsv"), delimiter="\t"))
    out = r_runs([], cases)
    flush(out)
    w = sys.stdout.write
    w(file_entry("validation/m15b_cases.tsv", "input", "the cases: objects, options, inputs (validation/python/m15b_cases.py)") + "\n")
    for f in sorted(glob.glob("data/clustering/m15b/inputs/*/*")):
        w(file_entry(f, "input", f"a case's input: {os.path.basename(f)}", dataset=f.split("/")[4]) + "\n")
    f = "data/clustering/logs/m15b/regress_vectors.txt"
    if os.path.isfile(f):
        w(file_entry(f, "check", "validation/R/regress_vectors.R's log: the code path's functions against the source tarball's, the vectors") + "\n")
    for f in sorted(glob.glob("tests/fixtures/rcompat/linpack_*") + glob.glob("tests/fixtures/clustering/m15b/**/*", recursive=True)
                    + glob.glob("tests/fixtures/clustering/percent_mt/**/*", recursive=True)):
        if os.path.isfile(f):
            w(file_entry(f, "fixture", "a committed fixture of M15b's tests (validation/slurm/fixtures_m15b.sh)") + "\n")
    for f in sorted(glob.glob("data/clustering/m15b/saved/*/*")):
        if os.path.isfile(f):
            w(file_entry(f, "saved-output", f"the saved object's percent.mt (validation/R/export_percent_mt.R): {os.path.basename(f)}",
                         dataset=f.split("/")[4]) + "\n")
    for f in sorted(glob.glob("data/clustering/m15b/percent_mt_sct/*.json")):
        w(file_entry(f, "check", "PercentageFeatureSet() on the SCT and the RNA assay against the saved percent.mt",
                     dataset=os.path.basename(f)[:-5]) + "\n")
    for f in sorted(glob.glob("data/clustering/m15b/percent_mt_rna/*.json")):
        w(file_entry(f, "check", "PercentageFeatureSet() on the SCT and the RNA assay against the saved percent.mt and scrust's",
                     dataset=os.path.basename(f)[:-5]) + "\n")
    for f in sorted(glob.glob(f"data/clustering/m15b/rust/{a.label}/*/*/*/*")):
        if os.path.isfile(f) and os.path.basename(f) not in ("stderr.txt",):
            parts = f.split("/")
            role = "check" if os.path.basename(f).startswith(("validate_", "refusal")) else "run-record"
            w(file_entry(f, role, f"scrust's run of case {parts[5]}, {parts[6]} profile: {parts[7]}", dataset=parts[4]) + "\n")
    if a.revalidate:
        for f in sorted(glob.glob(f"data/clustering/m15b/revalidate/{a.revalidate}/**/*", recursive=True)):
            if os.path.isfile(f):
                w(file_entry(f, "check", f"the validation runs validated again by the final binary: {os.path.relpath(f, 'data/clustering/m15b/revalidate')}") + "\n")
    for f in sorted(glob.glob(f"data/clustering/m15b/saved_rust/{a.label}/summary.tsv") + glob.glob(f"data/clustering/m15b/saved_rust/{a.label}/*/*")):
        if os.path.isfile(f) and os.path.basename(f) != "stderr.txt":
            w(file_entry(f, "check" if f.endswith((".json", ".tsv")) else "run-record", f"scrust's percent.mt against the saved object's: {os.path.basename(f)}") + "\n")
    for f in sorted(glob.glob("data/clustering/m15b/floor/*")):
        w(file_entry(f, "check", f"validation/python/m15b_floor.py: {os.path.basename(f)}") + "\n")
    for f in sorted(glob.glob(f"data/clustering/m15b/unchanged/{a.label}/*")):
        w(file_entry(f, "check", f"without the options, against M15's runs: {os.path.basename(f)}") + "\n")
    for f in sorted(glob.glob(f"data/doubletfinder/*/rust/{a.label}/*_m15b/checks/*") + glob.glob(f"data/doubletfinder/*/rust/{a.label}/*_m15b/time_*.txt")
                    + glob.glob(f"data/doubletfinder/*/rust/{a.label}/*_m15b/fingerprint.json") + glob.glob(f"data/doubletfinder/*/rust/{a.label}/*_m15b/inputs/*")):
        parts = f.split("/")
        role = "check" if "/checks/" in f else ("input" if "/inputs/" in f else "run-record")
        w(file_entry(f, role, f"DoubletFinder's clusterings with the options, {parts[5][:-5]} profile: {os.path.basename(f)}", dataset=parts[2]) + "\n")
    if a.cargo_job:
        for f in sorted(glob.glob(f"data/clustering/m15b/cargo_tests/{a.cargo_job}/*")):
            w(file_entry(f, "check", f"cargo test --workspace, debug and release: {os.path.basename(f)}") + "\n")
    if a.tests_job:
        for f in sorted(glob.glob(f"data/clustering/m15b/tests/{a.tests_job}/*.log")):
            w(file_entry(f, "check", f"the loaders' own tests: {os.path.basename(f)}") + "\n")
    for b in a.bin:
        w(file_entry(b, "binary", "a pinned scrust binary of M15b's runs") + "\n")


if __name__ == "__main__":
    main()

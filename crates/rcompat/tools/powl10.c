/* Generates crates/rcompat/src/powl10.rs: glibc's powl(10, k) for every k that R's number
 * formatting can pass it (format.c, scientific(): kp = floor(log10(|x|)) - 14 for |kp| > 27, so
 * k in [-338, 294] for finite doubles; the table covers [-340, 300]).
 *
 * glibc's x86-64 powl is not correctly rounded for every k (65 of the 701 values in [-360, 340]
 * are one ulp off), so the table holds the library's own results, which R uses.
 *
 * Build and run with the project env (source env.sh) on x86-64 Linux:
 *   x86_64-conda-linux-gnu-cc -O0 -o powl10 crates/rcompat/tools/powl10.c -lm
 *   ./powl10 > crates/rcompat/src/powl10.rs
 */
#include <gnu/libc-version.h>
#include <math.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>

#define KMIN (-340)
#define KMAX 300

int main(void)
{
    printf("// Generated by crates/rcompat/tools/powl10.c with glibc %s (x86-64); do not edit.\n",
           gnu_get_libc_version());
    printf("//! glibc's `powl(10, k)` as x87 extended values (sign and exponent, significand), for\n"
           "//! k in [%d, %d]: the scaling R's `formatReal` uses for numbers outside [1e-13, 1e42).\n\n",
           KMIN, KMAX);
    printf("pub(crate) const POWL10_KMIN: i32 = %d;\n\n", KMIN);
    printf("pub(crate) const POWL10: [(u16, u64); %d] = [\n", KMAX - KMIN + 1);
    for (int k = KMIN; k <= KMAX; k++) {
        long double v = powl(10.0L, (long double) k);
        unsigned char b[16];
        uint64_t m;
        uint16_t se;
        memset(b, 0, sizeof b);
        memcpy(b, &v, 10);
        memcpy(&m, b, 8);
        memcpy(&se, b + 8, 2);
        printf("    (0x%04x, 0x%016llx), // 1e%d\n", se, (unsigned long long) m, k);
    }
    printf("];\n");
    return 0;
}
